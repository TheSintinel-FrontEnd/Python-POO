
#aca se calculan las sumas y restas


def Suma (num1,num2): #Funcion de suma
    
    suma = num1 + num2 #Hacemos la suma
    
    return f"La sumatoria del los numeros es {suma}" #Retornamos el resultado de la funcion


def Resta (num1,num2): #Funcion de resta
    
    resta = num1 - num2 #Hacemos la resta
    
    return f"La resta de los dos numero es {resta}" #Retornamos la resta
