
#Comparador de numeros

valor1 = input ("Digite un numero: ")
valor2 = input ("Digite otro numero: ")

#Convirtiendo el string en numero enteros

numero1 = int(valor1)

numero2 = int(valor2)

#Comparando los numeros ingresados


if numero1 == numero2:
    
    print(f"los numeros son iguales y son {numero1} y {numero2}")
else:
    print(f"Estos numero no son iguales fijate, el primer numero es {numero1} y el otro es {numero2}")


